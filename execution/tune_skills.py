def run(shared):
    shared=Path(shared);state=json.loads((shared/'state.json').read_text(encoding='utf-8'))
    backup=shared/'backups'/state['transaction']/'before-tuning'
    changed=[]
    for name in sorted(REPLACEMENTS.keys()|DESCRIPTIONS.keys()):
        path=shared/'skills'/name/'SKILL.md'
        if not path.exists():continue
        original=path.read_text(encoding='utf-8-sig')
        if name in REPLACEMENTS:
            description,body=REPLACEMENTS[name]
            content='---\nname: '+name+'\ndescription: '+json.dumps(description,ensure_ascii=False)+'\n---\n\n'+body
        else:
            content=re.sub(r'^description:.*(?:\n[ \t]+[^\n]+)*',
                           'description: '+json.dumps(DESCRIPTIONS[name],ensure_ascii=False),original,count=1,flags=re.M)
            if name=='chaily-project-map':
                parts=content.split('---',2)
                detail=path.parent/'DETAILS.md'
                if not detail.exists():detail.write_text(parts[2].lstrip(),encoding='utf-8')
                content='---'+parts[1]+'---\n\n# Карта Chaily\n\nНайди нужный раздел в [DETAILS.md](DETAILS.md) по заголовку или ключевому слову и прочитай его. Полная карта не нужна для каждой правки. Для изменения межрепозиторного API используй chaily-cross-repo-sync-fix. Графы и touchpoints.json находятся рядом со скиллом.\n'
        if content!=original:
            saved=backup/name/'SKILL.md';saved.parent.mkdir(parents=True,exist_ok=True)
            if not saved.exists():shutil.copy2(path,saved)
            path.write_text(content,encoding='utf-8')
            changed.append({'skill':name,'before_chars':len(original),'after_chars':len(content)})
    out=shared/'tuning.json';out.write_text(json.dumps(changed,ensure_ascii=False,indent=2),encoding='utf-8')
    return changed


if __name__=='__main__':
    print(json.dumps(run(Path.home()/'.agent-harness'),ensure_ascii=False,indent=2))
